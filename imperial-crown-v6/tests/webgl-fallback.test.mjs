import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const dom = new JSDOM(readFileSync(new URL('../index.html', import.meta.url), 'utf8'), { url:'https://example.test/', pretendToBeVisual:true });
const { window } = dom;
const gradient = { addColorStop() {} };
const ctx = new Proxy({ createLinearGradient:() => gradient, createRadialGradient:() => gradient, measureText:() => ({ width:8 }) }, { get:(o,k) => k in o ? o[k] : () => {}, set:() => true });
window.HTMLCanvasElement.prototype.getContext = function(kind) { return kind === '2d' ? ctx : null; };
globalThis.window = window;
globalThis.document = window.document;
Object.defineProperty(globalThis, 'navigator', { value:window.navigator, configurable:true });
globalThis.HTMLElement = window.HTMLElement;
globalThis.HTMLCanvasElement = window.HTMLCanvasElement;
globalThis.localStorage = window.localStorage;
globalThis.requestAnimationFrame = window.requestAnimationFrame = fn => setTimeout(() => fn(performance.now()), 0);
globalThis.cancelAnimationFrame = clearTimeout;
const { App } = await import('../src/main.js');
const app = new App();
await app.boot();
assert(document.getElementById('bootScreen').classList.contains('hidden'), 'boot overlay hides hardware error');
assert(!document.getElementById('modalScreen').classList.contains('hidden'), 'hardware error not displayed');
assert.equal(document.getElementById('modalTitle').textContent, 'WebGL2 required');
assert(document.getElementById('modalBody').textContent.includes('Android System WebView'), 'no actionable Android recovery guidance');
assert(document.getElementById('btnStart').disabled, 'cannot start without a renderer');
document.getElementById('modalClose').click();
assert(document.getElementById('modalScreen').classList.contains('hidden'), 'error cannot be dismissed');
assert(!document.getElementById('menuScreen').classList.contains('hidden'), 'no menu after error');
console.log('WEBGL FALLBACK CHECKS PASSED');
dom.window.close();
