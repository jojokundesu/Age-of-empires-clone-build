import { generateWorld } from '../src/sim/worldgen.js';
import { Game } from '../src/sim/game.js';
const g = new Game({ world: generateWorld(20261), civ: 'franks', mode: 'sandbox', difficulty: 'standard' });
g.start();
const u = g.units.find(x=>x.team===1);
const N = 100000;
let t = process.hrtime.bigint();
let ok = 0;
for (let i=0;i<N;i++) if (g.isPassable(-120 + (i%400)*0.1, 155 + (i%97)*0.05, u)) ok++;
console.log('isPassable', (Number(process.hrtime.bigint()-t)/N*1000).toFixed(2), 'us/call', ok, 'ok');
t = process.hrtime.bigint();
for (let i=0;i<N;i++) g.world.height.sample(-120 + (i%400)*0.1, 155 + (i%97)*0.05);
console.log('height.sample', (Number(process.hrtime.bigint()-t)/N*1000).toFixed(2), 'us/call');
t = process.hrtime.bigint();
for (let i=0;i<N;i++) g.world.height.slope(-120 + (i%400)*0.1, 155 + (i%97)*0.05);
console.log('height.slope', (Number(process.hrtime.bigint()-t)/N*1000).toFixed(2), 'us/call');
t = process.hrtime.bigint();
for (let i=0;i<N;i++) g.buildingSpatial.query(-120 + (i%400)*0.1, 155 + (i%97)*0.05, 5);
