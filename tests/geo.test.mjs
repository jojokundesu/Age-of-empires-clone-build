/* Geometry integrity.

   Every model in the game is generated by `Geo`, so a single inverted winding
   silently makes a whole class of surfaces (tree canopies, domes, rocks) render
   black — the normals point into the object, the sun term disappears and only
   the ground hemisphere light survives. This suite proves the primitives are
   wound outwards, that no triangle is degenerate or NaN, and that the composed
   models stay inside their triangle budget.                                */
import { Geo, M, PART, MAT_SCALE } from '../src/gfx/geo.js';
import { BUILDING_TYPES, UNIT_TYPES, PROP_TYPES, buildBuilding, buildUnit, buildProp, census } from '../src/gfx/models.js';

let pass = 0;
const fails = [];
const check = (name, fn) => {
  try { fn(); pass++; console.log('  ok   ' + name); }
  catch (e) { fails.push(name + ': ' + (e && e.message)); console.log('  FAIL ' + name + ' — ' + (e && e.message)); }
};
const assert = (c, m) => { if (!c) throw new Error(m || 'assertion failed'); };

const STRIDE = 16;

/** Divergence-theorem volume: positive for outward (CCW) winding. */
function signedVolume(g) {
  const P = g.v, I = g.i;
  let v = 0;
  for (let t = 0; t < I.length; t += 3) {
    const a = I[t] * STRIDE, b = I[t + 1] * STRIDE, c = I[t + 2] * STRIDE;
    const ax = P[a], ay = P[a + 1], az = P[a + 2];
    const bx = P[b], by = P[b + 1], bz = P[b + 2];
    const cx = P[c], cy = P[c + 1], cz = P[c + 2];
    v += (ax * (by * cz - bz * cy) - ay * (bx * cz - bz * cx) + az * (bx * cy - by * cx)) / 6;
  }
  return v;
}

function audit(g, label) {
  const P = g.v;
  const n = P.length / STRIDE;
  assert(g.i.length % 3 === 0, `${label}: index count not a multiple of 3`);
  for (const idx of g.i) assert(idx >= 0 && idx < n, `${label}: index ${idx} out of range (${n} verts)`);
  for (let k = 0; k < n; k++) {
    const o = k * STRIDE;
    for (let f = 0; f < 3; f++) {
      assert(Number.isFinite(P[o + f]), `${label}: non-finite position in vertex ${k}`);
      assert(Number.isFinite(P[o + 3 + f]), `${label}: non-finite normal in vertex ${k}`);
      assert(Number.isFinite(P[o + 6 + f]), `${label}: non-finite uv in vertex ${k}`);
    }
    const len = Math.hypot(P[o + 3], P[o + 4], P[o + 5]);
    assert(Math.abs(len - 1) < 0.02, `${label}: normal ${len.toFixed(3)} not unit length at vertex ${k}`);
    const mat = P[o + 8];
    assert(mat >= 0 && mat < MAT_SCALE.length, `${label}: material ${mat} out of range`);
    assert(P[o + 15] >= 0 && P[o + 15] <= PART.EXTRA, `${label}: part id ${P[o + 15]} out of range`);
  }
}

check('box is wound outwards and closed', () => {
  const g = new Geo(); g.box(0, 0, 0, 2, 2, 2);
  const v = signedVolume(g);
  assert(Math.abs(v - 8) < 0.01, `volume ${v.toFixed(3)} != 8`);
  audit(g, 'box');
});

check('cylinder is wound outwards', () => {
  const seg = 12;
  const g = new Geo(); g.cyl(0, 0, 0, 1, 1, 2, seg, { capBottom: true });
  // a 12-gon inscribed in a unit circle has area 0.5*seg*sin(2π/seg)
  const exact = 0.5 * seg * Math.sin((Math.PI * 2) / seg) * 2;
  const v = signedVolume(g);
  assert(Math.abs(v - exact) < 0.01, `volume ${v.toFixed(3)} != ${exact.toFixed(3)}`);
});

check('cone is wound outwards', () => {
  const g = new Geo(); g.cone(0, 0, 0, 1, 2, 12);
  const v = signedVolume(g);
  assert(v > 0.5, `volume ${v.toFixed(3)} should be positive`);
  audit(g, 'cone');
});

check('sphere is wound outwards', () => {
  const g = new Geo(); g.sphere(0, 0, 0, 1, 12, 8);
  const v = signedVolume(g);
  assert(v > 3.4 && v < 4.3, `volume ${v.toFixed(3)} should be ~4/3π (4.19)`);
  audit(g, 'sphere');
});

check('tapered box has positive volume', () => {
  const g = new Geo(); g.taperBox(0, 0, 0, 3, 2, 3, 2, 2);
  assert(signedVolume(g) > 0, 'taperBox is inside-out');
  audit(g, 'taperBox');
});

check('plane / quad face points the way it is told', () => {
  const g = new Geo();
  g.quad(-1, 0, -1, 1, 0, -1, 1, 0, 1, -1, 0, 1);
  const ny = g.v[STRIDE + 4];
  assert(ny < -0.99, `expected a downward normal, got ${ny.toFixed(2)}`);
});

check('every primitive starts a fresh part without leaking state', () => {
  const g = new Geo();
  g.part_(PART.ARM_R, 1, 2, 3).box(0, 0, 0, 1, 1, 1);
  for (let k = 0; k < g.v.length / STRIDE; k++) {
    const o = k * STRIDE;
    assert(g.v[o + 15] === PART.ARM_R, 'part id not applied');
    assert(g.v[o + 12] === 1 && g.v[o + 13] === 2 && g.v[o + 14] === 3, 'pivot not applied');
  }
});

check('the whole model library is well formed and inside budget', () => {
  const all = [];
  for (const t of BUILDING_TYPES) all.push([t, buildBuilding(t).geo]);
  for (const t of UNIT_TYPES) { const r = buildUnit(t); if (r) all.push([t, r.geo]); }
  for (const t of PROP_TYPES) all.push([t, buildProp(t).geo]);
  assert(all.length > 50, `only ${all.length} models built`);
  const bad = [];
  let tris = 0;
  for (const [name, geo] of all) {
    try { audit(geo, name); } catch (e) { bad.push(e.message); }
    tris += geo.i.length / 3;
  }
  assert(!bad.length, bad.slice(0, 6).join(' | '));
  const c = census();
  assert(c.total >= 18000 && c.total <= 26000, `triangle budget moved: ${c.total}`);
  console.log(`         ${all.length} models, ${c.total} triangles`);
});

check('distant props are cheap and the town centre is rich', () => {
  const c = census();
  assert(c.props.rock < 200, `rock prop is ${c.props.rock} tris`);
  assert(c.buildings.town_center >= c.props.rock, 'the hero building should carry more detail than a rock');
});

/* The village dressing that turned the town apron from clipped grass into a
   working settlement. They are tiny, they are instanced by the hundred, and
   they are the easiest thing in the project to break by accident: a prop with
   no material variety reads as a coloured lump, a prop taller than it claims
   floats or sinks, and one that blows the triangle budget costs every frame. */
check('the eight village props are cheap, varied and the right size', () => {
  const want = {
    crate: [0.3, 0.9], barrel: [0.4, 1.1], haystack: [1.2, 2.4], firewood: [0.2, 0.8],
    cart: [0.7, 1.6], well: [1.4, 2.6], fence: [0.7, 1.5], drying_rack: [0.8, 1.8]
  };
  for (const [type, [lo, hi]] of Object.entries(want)) {
    assert(PROP_TYPES.includes(type), `${type} missing from the prop catalogue`);
    const res = buildProp(type);
    const g = res.geo.finish ? res.geo.finish() : res.geo;
    const tris = g.i.length / 3;
    assert(tris >= 30 && tris <= 400, `${type} is ${tris} tris`);
    assert(g.i.length > 0 && g.v.length > 0, `${type} has no geometry`);
    assert(res.height >= lo && res.height <= hi, `${type} height ${res.height} outside ${lo}..${hi}`);
    const mats = new Set();
    for (let i = 8; i < g.v.length; i += 16) mats.add(g.v[i]);
    assert(mats.size >= 2, `${type} is painted with a single material: ${[...mats].join(',')}`);
  }
});

/* Props are placed with their origin on the terrain, so a prop whose geometry
   starts half a metre up is a floating barrel. And a "log" written with the
   cylinder helper's angular-start option instead of its axis option is not a
   log at all -- it is a 1.5 m pole standing in the grass, which is exactly what
   the meadows were full of. */
check('every prop stands on the ground it is placed on', () => {
  const floating = [];
  for (const type of PROP_TYPES) {
    const res = buildProp(type);
    if (!res) continue;
    const g = res.geo.finish ? res.geo.finish() : res.geo;
    let lo = Infinity, hi = -Infinity;
    for (let i = 1; i < g.v.length; i += STRIDE) { lo = Math.min(lo, g.v[i]); hi = Math.max(hi, g.v[i]); }
    // mines and boulders are allowed to sink into the hillside
    if (lo > 0.12) floating.push(`${type} floats at ${lo.toFixed(2)} m`);
    if (lo < -0.7) floating.push(`${type} sinks to ${lo.toFixed(2)} m`);
    assert(hi <= res.height * 1.45 + 0.05, `${type} reaches ${hi.toFixed(2)} m but declares ${res.height}`);
  }
  assert(!floating.length, floating.join(', '));
});

check('a log lies down and a fence stays thin', () => {
  const box = (type) => {
    const g = buildProp(type).geo;
    const geo = g.finish ? g.finish() : g;
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity, z0 = Infinity, z1 = -Infinity;
    for (let i = 0; i < geo.v.length; i += STRIDE) {
      x0 = Math.min(x0, geo.v[i]); x1 = Math.max(x1, geo.v[i]);
      y0 = Math.min(y0, geo.v[i + 1]); y1 = Math.max(y1, geo.v[i + 1]);
      z0 = Math.min(z0, geo.v[i + 2]); z1 = Math.max(z1, geo.v[i + 2]);
    }
    return { x: x1 - x0, y: y1 - y0, z: z1 - z0, low: y0 };
  };
  const log = box('log');
  assert(log.x > 1.2, `the log is only ${log.x.toFixed(2)} m long`);
  assert(log.y < 0.55, `the log stands ${log.y.toFixed(2)} m tall -- it is a pole, not a log`);
  assert(log.low < 0.1, 'the log floats');
  const fence = box('fence');
  assert(fence.x > 1.8 && fence.z < 0.2, `the fence run is ${fence.x.toFixed(2)} x ${fence.z.toFixed(2)} m`);
  const firewood = box('firewood');
  assert(firewood.z > 0.5 && firewood.y < 0.5, 'the firewood stack is a bundle of poles');
});

check('the brazier is a cheap prop whose flame sits at the firelight height', () => {
  const res = buildProp('brazier');
  const g = res.geo.finish();
  const tris = g.i.length / 3;
  assert(tris > 40 && tris < 400, `brazier is ${tris} tris (four of them draw every frame)`);
  assert(res.height > 1.4 && res.height < 2.0, `brazier height ${res.height} does not match the 1.6 m firelight slot`);
  // it must actually contain emissive geometry, otherwise it is just ironwork
  // (16 floats per vertex: pos, normal, uv, material, colour, pivot, part)
  const mats = new Set();
  for (let i = 8; i < g.v.length; i += 16) mats.add(g.v[i]);
  assert(mats.has(12), 'brazier has no glow-material vertices (no fire): ' + [...mats].join(','));
  assert(mats.size >= 3, 'brazier is painted with a single material: ' + [...mats].join(','));
  assert(PROP_TYPES.includes('brazier'), 'brazier missing from the prop catalogue');
});

if (fails.length) {
  console.error('\nGEOMETRY CHECKS FAILED\n' + fails.map((f) => ' - ' + f).join('\n'));
  process.exit(1);
}
console.log(`\nGEOMETRY CHECKS PASSED (${pass})`);
